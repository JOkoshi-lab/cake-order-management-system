CREATE TABLE cake (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    price INT NOT NULL
);

CREATE TABLE o_time (
    id VARCHAR(36) PRIMARY KEY,
    time TIME DEFAULT CURRENT_TIME
);

CREATE TABLE o_qtt (
    time_id VARCHAR(36) NOT NULL,
    cake_id INT NOT NULL,
    quantity INT NOT NULL,
    PRIMARY KEY (time_id, cake_id),
    CONSTRAINT fk_o_qtt_time FOREIGN KEY (time_id) REFERENCES o_time(id),
    CONSTRAINT fk_o_qtt_cake FOREIGN KEY (cake_id) REFERENCES cake(id)
);